#!/bin/bash

# Скрипт для пересборки и замены фронтенд контейнера
# Использование: ./rebuild-frontend.sh

set -e  # Остановить выполнение при ошибке

echo "🚀 Начинаем пересборку фронтенда..."

# Проверяем, что мы в правильной директории
if [ ! -f "docker-compose.yml" ]; then
    echo "❌ Ошибка: docker-compose.yml не найден. Запустите скрипт из корневой директории проекта."
    exit 1
fi

# Останавливаем фронтенд контейнер
echo "🛑 Останавливаем фронтенд контейнер..."
docker-compose stop frontend || echo "⚠️  Фронтенд контейнер не был запущен"

# Удаляем старый фронтенд контейнер
echo "🗑️  Удаляем старый фронтенд контейнер..."
docker-compose rm -f frontend || echo "⚠️  Старый контейнер не найден"

# Удаляем старый образ фронтенда
echo "🗑️  Удаляем старый образ фронтенда..."
docker rmi miscord-frontend 2>/dev/null || echo "⚠️  Старый образ не найден"

# Пересобираем фронтенд контейнер
echo "🔨 Пересобираем фронтенд контейнер..."
docker-compose build --no-cache frontend

# Запускаем новый фронтенд контейнер
echo "🚀 Запускаем новый фронтенд контейнер..."
docker-compose up -d frontend

# Проверяем статус контейнера
echo "⏳ Ожидаем запуска контейнера..."
sleep 5

# Проверяем, что контейнер запущен
if docker-compose ps frontend | grep -q "Up"; then
    echo "✅ Фронтенд успешно пересобран и запущен!"
    echo "📊 Статус контейнеров:"
    docker-compose ps
else
    echo "❌ Ошибка: Фронтенд контейнер не запустился"
    echo "📋 Логи контейнера:"
    docker-compose logs frontend
    exit 1
fi

echo "🎉 Пересборка фронтенда завершена успешно!"
