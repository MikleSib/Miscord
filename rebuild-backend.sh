#!/bin/bash

# Скрипт для пересборки и замены бэкенд контейнера
# Использование: ./rebuild-backend.sh

set -e  # Остановить выполнение при ошибке

echo "🚀 Начинаем пересборку бэкенда..."

# Проверяем, что мы в правильной директории
if [ ! -f "docker-compose.yml" ]; then
    echo "❌ Ошибка: docker-compose.yml не найден. Запустите скрипт из корневой директории проекта."
    exit 1
fi

# Останавливаем бэкенд контейнер
echo "🛑 Останавливаем бэкенд контейнер..."
docker-compose stop backend || echo "⚠️  Бэкенд контейнер не был запущен"

# Удаляем старый бэкенд контейнер
echo "🗑️  Удаляем старый бэкенд контейнер..."
docker-compose rm -f backend || echo "⚠️  Старый контейнер не найден"

# Удаляем старый образ бэкенда
echo "🗑️  Удаляем старый образ бэкенда..."
docker rmi miscord-backend 2>/dev/null || echo "⚠️  Старый образ не найден"

# Пересобираем бэкенд контейнер
echo "🔨 Пересобираем бэкенд контейнер..."
docker-compose build --no-cache backend

# Запускаем новый бэкенд контейнер
echo "🚀 Запускаем новый бэкенд контейнер..."
docker-compose up -d backend

# Проверяем статус контейнера
echo "⏳ Ожидаем запуска контейнера..."
sleep 5

# Проверяем, что контейнер запущен
if docker-compose ps backend | grep -q "Up"; then
    echo "✅ Бэкенд успешно пересобран и запущен!"
    echo "📊 Статус контейнеров:"
    docker-compose ps
else
    echo "❌ Ошибка: Бэкенд контейнер не запустился"
    echo "📋 Логи контейнера:"
    docker-compose logs backend
    exit 1
fi

echo "🎉 Пересборка бэкенда завершена успешно!"
